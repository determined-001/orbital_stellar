#!/usr/bin/env node
/**
 * Generates TypeScript types from the Horizon OpenAPI description.
 *
 * Source URL: https://raw.githubusercontent.com/stellar/stellar-docs/<REVISION>/openapi/horizon/bundled.yml
 * Revision: pinned to stellar/stellar-docs commit c933da4 (2026-07-30).
 * See https://github.com/stellar/stellar-docs/tree/main/openapi/horizon
 *
 * The revision is pinned deliberately: reading `main` makes every CI run
 * depend on a repository nobody here controls, so an upstream edit turns
 * unrelated PRs red. Bump SPEC_REVISION when you want to take upstream
 * changes, re-run this script, and commit the regenerated output - that
 * diff is the review surface for a Horizon schema change.
 *
 * Usage:
 *   node scripts/generate-horizon-types.mjs
 *
 * The generated file is written to packages/pulse-core/src/_raw-horizon.gen.ts
 * and is marked DO NOT EDIT.  To update, re-run this script and commit the
 * changed output (CI will fail if the committed output is stale).
 */
import { execFileSync } from "node:child_process";
import { writeFileSync, readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");

/** Pinned stellar/stellar-docs revision - see the header note before bumping. */
const SPEC_REVISION = "c933da4873e8f4c395956e7d638e9675aa9df02c";
const SPEC_URL = `https://raw.githubusercontent.com/stellar/stellar-docs/${SPEC_REVISION}/openapi/horizon/bundled.yml`;
const OUTPUT = resolve(repoRoot, "packages/pulse-core/src/_raw-horizon.gen.ts");

// ---------------------------------------------------------------------------
// Custom header – includes the pinned source URL so the output is self-documenting
// ---------------------------------------------------------------------------
const HEADER = `// ---------------------------------------------------------------------------
// DO NOT EDIT – This file is auto-generated by scripts/generate-horizon-types.mjs
// Source: ${SPEC_URL}
// Regenerate with: pnpm generate:horizon-types
// ---------------------------------------------------------------------------
`;

// ---------------------------------------------------------------------------
// 1. Download the bundled spec into a temporary file so openapi-typescript can
//    read it (its input must be a file URL or stdin, not a remote URL).
// ---------------------------------------------------------------------------
const tmpFile = resolve(repoRoot, "node_modules/.cache/horizon-openapi-bundled.yml");
execFileSync("mkdir", ["-p", dirname(tmpFile)]);

import { get } from "node:https";
import { createWriteStream } from "node:fs";

await new Promise((resolvePromise, reject) => {
  const file = createWriteStream(tmpFile);
  get(SPEC_URL, (response) => {
    if (response.statusCode !== 200) {
      reject(new Error(`HTTP ${response.statusCode} fetching ${SPEC_URL}`));
      return;
    }
    response.pipe(file);
    file.on("finish", () => file.close(resolvePromise));
  }).on("error", reject);
});

// ---------------------------------------------------------------------------
// 2. Run openapi-typescript with options matching the repo conventions
// ---------------------------------------------------------------------------
const outDir = dirname(OUTPUT);
execFileSync("mkdir", ["-p", outDir]);

execFileSync(
  "pnpm",
  [
    "exec",
    "openapi-typescript",
    tmpFile,
    "--output",
    OUTPUT,
    "--export-type",
    "--root-types",
    "--alphabetize",
  ],
  { cwd: repoRoot, stdio: "inherit" },
);

// ---------------------------------------------------------------------------
// 3. Prepend the custom header to the generated file
// ---------------------------------------------------------------------------
const generated = readFileSync(OUTPUT, "utf8");

// Replace the default openapi-typescript header with our custom one.
// The default header is the first line starting with "/*". We strip everything
// up to and including the first "*/" and replace it with our header.
const headerEnd = generated.indexOf("*/");
const cleaned = headerEnd !== -1 ? generated.slice(headerEnd + 2).trimStart() : generated;

writeFileSync(OUTPUT, `${HEADER}${cleaned}`, "utf8");

// ---------------------------------------------------------------------------
// 4. Format with the repo's prettier config
// ---------------------------------------------------------------------------
// `pnpm format:check` covers packages/**/*.ts, so unformatted generator output
// would fail lint - and CI's drift check would compare unformatted output
// against a formatted committed file and always report drift.
execFileSync("pnpm", ["exec", "prettier", "--write", OUTPUT], {
  cwd: repoRoot,
  stdio: "inherit",
});

// Clean up temp file
try {
  execFileSync("rm", [tmpFile]);
} catch {
  // best-effort
}

console.log(`\nWrote generated types to ${OUTPUT}`);
